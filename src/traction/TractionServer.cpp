    RID TractionServer::power_source_create() {
        /* The sources tick by the simulation's clock, each slice before the vehicles draw from
         * them - while there is a source to tick. No disconnect on the
         * server's death: callable_mp reports this instance as the callable's object, so the
         * engine drops the connection when the instance dies. */
        if (power_sources.is_empty()) {
            SimulationServer *simulation = SimulationServer::get_instance();
            ERR_FAIL_NULL_V(simulation, RID());
            simulation->connect(
                    SimulationServer::simulation_advanced_signal,
                    callable_mp(this, &TractionServer::_on_simulation_advanced));
        }
        next_power_source_id += 1;
        const RID rid = UtilityFunctions::rid_from_int64(next_power_source_id);
        power_sources.insert(rid, PowerSource());
        return rid;
    }

    void TractionServer::power_source_set_params(
            const RID &p_power_source, const String &p_name, const double p_nominal_voltage,
            const double p_voltage_frequency, const double p_internal_resistance, const double p_max_output_current,
            const double p_fast_fuse_timeout, const int p_fast_fuse_repetition, const double p_slow_fuse_timeout,
            const bool p_recuperation, const bool p_is_autogenerated, const bool p_is_section) {
        PowerSource *source = power_sources.getptr(p_power_source);
        if (source == nullptr) {
            return;
        }
        source->name = p_name;
        source->nominal_voltage = p_nominal_voltage;
        source->voltage_frequency = p_voltage_frequency;
        source->internal_resistance = p_internal_resistance;
        source->max_output_current = p_max_output_current;
        source->fast_fuse_timeout = p_fast_fuse_timeout;
        source->fast_fuse_repetition = p_fast_fuse_repetition;
        source->slow_fuse_timeout = p_slow_fuse_timeout;
        source->recuperation = p_recuperation;
        source->is_autogenerated = p_is_autogenerated;
        source->is_section = p_is_section;
        if (!p_name.is_empty()) {
            power_sources_by_name.insert(p_name, p_power_source);
        }
    }

    void TractionServer::power_source_set_nominal_voltage(const RID &p_power_source, const double p_voltage) {
        PowerSource *source = power_sources.getptr(p_power_source);
        ERR_FAIL_NULL(source);
        source->nominal_voltage = p_voltage;
    }

    double TractionServer::power_source_get_nominal_voltage(const RID &p_power_source) const {
        const PowerSource *source = power_sources.getptr(p_power_source);
        ERR_FAIL_NULL_V(source, 0.0);
        return source->nominal_voltage;
    }

    RID TractionServer::power_source_get_rid_by_name(const String &p_name) const {
        const RID *rid = power_sources_by_name.getptr(p_name);
        return rid != nullptr ? *rid : RID();
    }

    void TractionServer::power_source_free(const RID &p_power_source) {
        const PowerSource *source = power_sources.getptr(p_power_source);
        if (source == nullptr) {
            return;
        }
        const RID *named = power_sources_by_name.getptr(source->name);
        if (named != nullptr && *named == p_power_source) {
            power_sources_by_name.erase(source->name);
        }
        power_sources.erase(p_power_source);
        _power_source_freed(p_power_source);
        if (power_sources.is_empty()) {
            SimulationServer *simulation = SimulationServer::get_instance();
            ERR_FAIL_NULL(simulation);
            simulation->disconnect(
                    SimulationServer::simulation_advanced_signal,
                    callable_mp(this, &TractionServer::_on_simulation_advanced));
        }
    }

    RID TractionServer::wire_create() {
        next_wire_id += 1;
        const RID rid = UtilityFunctions::rid_from_int64(next_wire_id);
        wires.insert(rid, Wire());
        return rid;
    }

    void TractionServer::wire_set_params(
            const RID &p_wire, const Vector3 &p_p1, const Vector3 &p_p2, const String &p_power_supply_name,
            const double p_nominal_voltage, const double p_max_current, const double p_resistivity) {
        Wire *wire = wires.getptr(p_wire);
        if (wire == nullptr) {
            return;
        }
        wire->p1 = p_p1;
        wire->p2 = p_p2;
        wire->power_supply_name = p_power_supply_name;
        wire->nominal_voltage = p_nominal_voltage;
        wire->max_current = p_max_current;
        wire->resistivity = p_resistivity;
        Rect2 rect(Vector2(p_p1.x, p_p1.z), Vector2());
        rect = rect.expand(Vector2(p_p2.x, p_p2.z));
        spatial_index->remove(p_wire);
        spatial_index->add(p_wire, rect.grow(WIRE_AABB_MARGIN));
    }

    void TractionServer::wire_set_parallel(const RID &p_wire, const String &p_parallel_name) {
        if (Wire *wire = wires.getptr(p_wire); wire != nullptr) {
            wire->parallel_name = p_parallel_name;
        }
    }

    void TractionServer::wire_free(const RID &p_wire) {
        spatial_index->remove(p_wire);
        wires.erase(p_wire);
        _wire_freed(p_wire);
    }

    double TractionServer::wire_get_voltage(
            const RID &p_wire, const double /* p_assumed_voltage */, const double /* p_current */) const {
        const Wire *wire = wires.getptr(p_wire);
        return wire != nullptr ? wire->nominal_voltage : 0.0;
    }

    Dictionary TractionServer::wire_find_above_with_height(
            const Vector3 & /* p_position */, const Vector3 & /* p_up */, const Vector3 & /* p_forward */,
            const Vector3 & /* p_left */, const double /* p_width */, const double /* p_horn_width */) const {
        Dictionary result;
        result["rid"] = RID();
        result["height"] = INFINITY;
        return result;
    }

    Dictionary TractionServer::wire_follow_above(
            const RID & /* p_from_wire */, const Vector3 &p_position, const Vector3 &p_up, const Vector3 &p_forward,
            const Vector3 &p_left, const double p_width, const double p_horn_width) const {
        return wire_find_above_with_height(p_position, p_up, p_forward, p_left, p_width, p_horn_width);
    }
